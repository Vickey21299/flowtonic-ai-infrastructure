import type { InvestigationMode } from '@/api/types'
import { Badge } from '@/components/ui/badge'

/** Compact mode label for lists. A mock run is never presented as AI output. */
export function ModeBadge({ mode }: { mode: InvestigationMode }) {
  return mode === 'mock' ? (
    <Badge variant="inverse" title="MOCK INVESTIGATION — not generated by an AI model">
      Mock — not AI
    </Badge>
  ) : (
    <Badge variant="warning">AI-generated</Badge>
  )
}
