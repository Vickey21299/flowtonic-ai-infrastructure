import { Bot, FlaskConical, PencilLine } from 'lucide-react'
import { cn } from '@/lib/utils'

export type AiLabelKind = 'mock' | 'ai' | 'edited'

const content: Record<AiLabelKind, { text: string; className: string; icon: typeof Bot }> = {
  mock: {
    text: 'MOCK INVESTIGATION — not generated by an AI model',
    className: 'border-foreground bg-foreground text-background font-semibold tracking-wide',
    icon: FlaskConical,
  },
  ai: {
    text: 'AI-generated — unverified',
    className: 'border-status-warning/40 bg-status-warning-bg text-status-warning font-semibold',
    icon: Bot,
  },
  edited: {
    text: 'Edited by analyst',
    className: 'border-accent/30 bg-accent/10 text-accent font-medium',
    icon: PencilLine,
  },
}

interface AiLabelProps {
  kind: AiLabelKind
  /** `lg` for the persistent banner at the top of an investigation. */
  size?: 'sm' | 'lg'
  className?: string
}

/** Prominent provenance label for investigation content. */
export function AiLabel({ kind, size = 'sm', className }: AiLabelProps) {
  const c = content[kind]
  const Icon = c.icon
  return (
    <span
      className={cn(
        'inline-flex items-center gap-1.5 rounded border',
        size === 'lg' ? 'px-3 py-1.5 text-xs sm:text-sm' : 'px-2 py-0.5 text-xs',
        c.className,
        className,
      )}
    >
      <Icon className={size === 'lg' ? 'h-4 w-4 shrink-0' : 'h-3.5 w-3.5 shrink-0'} aria-hidden />
      {c.text}
    </span>
  )
}

export type DataNature = 'observed' | 'calculated' | 'estimated' | 'hypothetical'

const natureStyle: Record<DataNature, { label: string; className: string }> = {
  observed: { label: 'Observed', className: 'border-border bg-muted text-foreground' },
  calculated: { label: 'Calculated', className: 'border-accent/30 bg-accent/10 text-accent' },
  estimated: { label: 'Estimated — not realised', className: 'border-dashed border-muted-foreground/50 bg-surface text-muted-foreground' },
  hypothetical: { label: 'Hypothesis — unverified', className: 'border-dashed border-status-warning/50 bg-surface text-status-warning' },
}

/** Labels where a number or statement comes from, so estimates never read as realised facts. */
export function SourceLabel({ nature, className }: { nature: DataNature; className?: string }) {
  const s = natureStyle[nature]
  return (
    <span className={cn('inline-flex items-center rounded border px-1.5 py-0.5 text-2xs font-medium uppercase tracking-wider', s.className, className)}>
      {s.label}
    </span>
  )
}
